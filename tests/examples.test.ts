/**
 * The bundled examples are the demo programs, so they get pinned here: they
 * must load into a workspace and generate exactly the MicroPython we expect.
 */
import * as Blockly from 'blockly';
import { describe, expect, it } from 'vitest';
import { registerBlocks } from '../src/blocks';
import { EXAMPLES } from '../src/examples';
import { generateProgram } from '../src/generators/assemble';

registerBlocks();

function codeFor(id: string): string {
  const example = EXAMPLES.find((candidate) => candidate.id === id);
  if (!example) throw new Error(`no example named ${id}`);
  const workspace = new Blockly.Workspace();
  Blockly.serialization.workspaces.load(example.project.workspace, workspace);
  return generateProgram(workspace).code;
}

describe('example projects', () => {
  it('all load and produce code', () => {
    for (const example of EXAMPLES) {
      const code = codeFor(example.id);
      expect(code.startsWith('# Code automatically generated by PicoBlocks')).toBe(true);
      expect(code.length).toBeGreaterThan(60);
    }
  });

  it('blink', () => {
    expect(codeFor('blink')).toBe(
      [
        '# Code automatically generated by PicoBlocks',
        'from machine import Pin',
        'import time',
        '',
        'while True:',
        '    Pin("LED", Pin.OUT).value(1)',
        '    time.sleep(0.5)',
        '    Pin("LED", Pin.OUT).value(0)',
        '    time.sleep(0.5)',
        '',
      ].join('\n'),
    );
  });

  it('button, LED and buzzer', () => {
    expect(codeFor('button-buzzer')).toBe(
      [
        '# Code automatically generated by PicoBlocks',
        'from machine import Pin, PWM',
        'import time',
        '',
        'pwm_15 = PWM(Pin(15))',
        '',
        'while True:',
        '    if Pin(14, Pin.IN, Pin.PULL_UP).value() == 0:',
        '        Pin("LED", Pin.OUT).value(1)',
        '        pwm_15.freq(880)',
        '        pwm_15.duty_u16(32768)',
        '        time.sleep_ms(100)',
        '        pwm_15.duty_u16(0)',
        '    else:',
        '        Pin("LED", Pin.OUT).value(0)',
        '    time.sleep_ms(50)',
        '',
      ].join('\n'),
    );
  });

  it('temperature alert', () => {
    expect(codeFor('temperature-alert')).toBe(
      [
        '# Code automatically generated by PicoBlocks',
        'from machine import Pin, PWM, ADC',
        'import time',
        '',
        'temp_sensor = ADC(4)',
        'pwm_15 = PWM(Pin(15))',
        '',
        'def read_temperature():',
        '    # The RP2040 sensor reads 0.706 V at 27 C,',
        '    # and drops by 1.721 mV for every degree above that.',
        '    volts = temp_sensor.read_u16() * 3.3 / 65535',
        '    return round(27 - (volts - 0.706) / 0.001721, 1)',
        '',
        'threshold = 0',
        'temperature = 0',
        '',
        'threshold = 28',
        '',
        'while True:',
        '    temperature = read_temperature()',
        "    print('temperature: ' + str(temperature))",
        '    if temperature > threshold:',
        '        Pin("LED", Pin.OUT).value(1)',
        '        pwm_15.freq(880)',
        '        pwm_15.duty_u16(32768)',
        '        time.sleep_ms(200)',
        '        pwm_15.duty_u16(0)',
        "        print('ALERT')",
        '    else:',
        '        Pin("LED", Pin.OUT).value(0)',
        "        print('normal')",
        '    time.sleep(1)',
        '',
      ].join('\n'),
    );
  });
});
