import { describe, expect, it } from 'vitest';
import { decodeUtf8 } from '../../src/serial/bytes';
import { ConnectionLostError, describeError, PythonError } from '../../src/serial/errors';
import { PicoConnectionManager } from '../../src/serial/PicoConnectionManager';
import { FakePico, type FakePicoOptions } from '../../src/dev/simulatedPico';

function connected(options: FakePicoOptions = {}) {
  const board = new FakePico(options);
  const manager = new PicoConnectionManager();
  const terminal: string[] = [];
  manager.onTerminalData((data) => terminal.push(decodeUtf8(data)));
  manager.attach(board);
  return { board, manager, terminal, output: () => terminal.join('') };
}

async function waitFor(check: () => boolean, timeoutMs = 3000): Promise<void> {
  const deadline = Date.now() + timeoutMs;
  while (!check()) {
    if (Date.now() > deadline) throw new Error('timed out waiting for condition');
    await new Promise((resolve) => setTimeout(resolve, 5));
  }
}

const BLINK = {
  code: '# Code automatically generated by PicoBlocks\nfrom machine import Pin\n\nwhile True:\n    Pin("LED", Pin.OUT).value(1)\n',
  pwmPins: [],
  hasCode: true,
};

describe('connection manager', () => {
  it('reports connected once a board is attached', () => {
    const { manager } = connected();
    expect(manager.getState().status).toBe('connected');
    expect(manager.getState().device).toEqual({
      usbVendorId: 0x2e8a,
      usbProductId: 0x0005,
    });
  });

  it('passes board output through to the terminal when idle', async () => {
    const { board, output } = connected();
    board.emitStdout('hello from the REPL\r\n');
    await waitFor(() => output().includes('hello from the REPL'));
  });

  it('runs a program, streams its output, and stops it', async () => {
    const { board, manager, output } = connected();
    const running = manager.run(BLINK);
    await waitFor(() => manager.getState().status === 'running');

    board.emitStdout('tick\r\n');
    await waitFor(() => output().includes('tick'));

    await manager.stop();
    await running;

    expect(manager.getState().status).toBe('connected');
    expect(output()).toContain('-- stopped --');
    expect(output()).not.toContain('KeyboardInterrupt');
    expect(board.executed[0]).toContain('while True:');
    // One soft reset before the run, one after Stop to quieten the pins.
    expect(board.softResets).toBe(2);
  });

  it('silences PWM pins after a stop', async () => {
    const { board, manager } = connected();
    const running = manager.run({ ...BLINK, pwmPins: [15, 16] });
    await waitFor(() => manager.getState().status === 'running');
    await manager.stop();
    await running;
    const cleanup = board.executed.at(-1) ?? '';
    expect(cleanup).toContain('for _pin in (15, 16,):');
    expect(cleanup).toContain('Pin(_pin, Pin.OUT).value(0)');
  });

  it('surfaces a program error as a PythonError and prints it', async () => {
    const { manager, output } = connected({
      executor: () => ({
        stdout: 'starting\r\n',
        stderr:
          'Traceback (most recent call last):\r\n  File "<stdin>", line 4, in <module>\r\nValueError: invalid pin\r\n',
      }),
    });
    await expect(manager.run(BLINK)).rejects.toBeInstanceOf(PythonError);
    expect(output()).toContain('starting');
    expect(output()).toContain('ValueError: invalid pin');
    expect(manager.getState().status).toBe('connected');
  });

  it('saves a file to the board and reads it back byte for byte', async () => {
    const { board, manager } = connected();
    // Quotes, backslashes and control bytes must survive the escaping.
    const source = `print('it\\'s "fine"')\n# \\x03 °C café\n${'x'.repeat(900)}\n`;
    await manager.saveFile('/main.py', source);
    expect(decodeUtf8(board.files.get('/main.py')!)).toBe(source);

    const readBack = await manager.readBoardFile('/main.py');
    expect(decodeUtf8(readBack)).toBe(source);
  });

  it('leaves the old file alone when an upload fails part way', async () => {
    const { board, manager } = connected();
    await manager.saveFile('/main.py', 'print("good")\n');

    let chunks = 0;
    const original = board.files.get('/main.py')!;
    // Make the third chunk fail, as a flaky cable would.
    const executor = board['executor' as keyof FakePico] as unknown;
    void executor;
    (board as unknown as { executor: (code: string) => unknown }).executor = (
      code: string,
    ) => {
      if (code.startsWith('_w(') && ++chunks === 3) {
        return { stdout: '', stderr: 'OSError: [Errno 28] ENOSPC\r\n' };
      }
      return { stdout: '', stderr: '' };
    };

    await expect(manager.saveFile('/main.py', 'x'.repeat(2000))).rejects.toThrow();
    expect(decodeUtf8(board.files.get('/main.py')!)).toBe(decodeUtf8(original));
  });

  it('lists files with sizes and free space', async () => {
    const { manager } = connected({
      files: { '/main.py': 'print(1)\n', '/lib/thing.py': 'x = 1\n' },
    });
    const listing = await manager.listFiles('/');
    expect(listing.entries.map((entry) => entry.name)).toEqual(['lib', 'main.py']);
    expect(listing.entries[1]).toMatchObject({
      name: 'main.py',
      path: '/main.py',
      isDir: false,
      size: 9,
    });
    expect(listing.freeBytes).toBeLessThan(listing.totalBytes);
  });

  it('explains a missing file in plain language', async () => {
    const { manager } = connected();
    const error = await manager.deleteEntry('/nope.py', false).catch((e) => e);
    expect(error).toBeInstanceOf(PythonError);
    expect(describeError(error)).toBe('There is no file with that name on the Pico.');
    // The failed operation must not leave the manager stuck.
    expect(manager.getState().status).toBe('connected');
  });

  it('recovers cleanly when the cable is pulled mid-operation', async () => {
    const { board, manager } = connected();
    const saving = manager.saveFile('/main.py', 'x'.repeat(4000));
    setTimeout(() => board.unplug(), 10);
    await expect(saving).rejects.toBeInstanceOf(ConnectionLostError);
    expect(manager.getState().status).toBe('disconnected');
  });

  it('runs board jobs one at a time', async () => {
    const { board, manager } = connected({ files: { '/main.py': 'print(1)\n' } });
    const [listing, ...rest] = await Promise.all([
      manager.listFiles('/'),
      manager.saveFile('/other.py', 'print(2)\n'),
      manager.listFiles('/'),
    ]);
    expect(listing.entries).toHaveLength(1);
    expect(rest).toHaveLength(2);
    expect(decodeUtf8(board.files.get('/other.py')!)).toBe('print(2)\n');
    expect(manager.getState().status).toBe('connected');
  });

  it('forwards typed input to a running program', async () => {
    const { board, manager } = connected();
    const running = manager.run(BLINK);
    await waitFor(() => manager.getState().status === 'running');
    manager.sendTerminalInput('hi');
    await waitFor(() => board.stdin === 'hi');
    await manager.stop();
    await running;
  });
});
