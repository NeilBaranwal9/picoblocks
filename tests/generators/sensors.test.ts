import { describe, expect, it } from 'vitest';
import { forever, generate, importsOf } from '../helpers';

describe('sensor blocks', () => {
  it('reads an ADC pin', () => {
    const code = generate([
      forever({
        type: 'debug_print',
        inputs: { TEXT: { block: { type: 'analog_read', fields: { PIN: '27' } } } },
      }),
    ]);
    expect(code).toContain('    print(ADC(Pin(27)).read_u16())');
  });

  it('reads a button as active low with the internal pull-up', () => {
    const code = generate([
      forever({
        type: 'controls_if',
        inputs: {
          IF0: { block: { type: 'button_pressed', fields: { PIN: '14' } } },
          DO0: { block: { type: 'onboard_led', fields: { STATE: '1' } } },
        },
      }),
    ]);
    expect(code).toContain('    if Pin(14, Pin.IN, Pin.PULL_UP).value() == 0:');
  });

  it('emits the onboard temperature helper once', () => {
    const code = generate([
      forever(
        {
          type: 'debug_print',
          inputs: { TEXT: { block: { type: 'read_temperature' } } },
        },
        {
          type: 'debug_print',
          inputs: { TEXT: { block: { type: 'read_temperature' } } },
        },
      ),
    ]);
    expect(code).toBe(
      [
        '# Code automatically generated by PicoBlocks',
        'from machine import ADC',
        '',
        'temp_sensor = ADC(4)',
        '',
        'def read_temperature():',
        '    # The RP2040 sensor reads 0.706 V at 27 C,',
        '    # and drops by 1.721 mV for every degree above that.',
        '    volts = temp_sensor.read_u16() * 3.3 / 65535',
        '    return round(27 - (volts - 0.706) / 0.001721, 1)',
        '',
        'while True:',
        '    print(read_temperature())',
        '    print(read_temperature())',
        '',
      ].join('\n'),
    );
    expect(importsOf(code)).toEqual(['from machine import ADC']);
  });

  it('compares a sensor reading against a threshold', () => {
    const code = generate([
      forever({
        type: 'controls_if',
        inputs: {
          IF0: {
            block: {
              type: 'logic_compare',
              fields: { OP: 'GT' },
              inputs: {
                A: { block: { type: 'read_temperature' } },
                B: { shadow: { type: 'math_number', fields: { NUM: 28 } } },
              },
            },
          },
          DO0: { block: { type: 'debug_print', inputs: { TEXT: { shadow: { type: 'text', fields: { TEXT: 'ALERT' } } } } } },
        },
      }),
    ]);
    expect(code).toContain('    if read_temperature() > 28:');
    expect(code).toContain("        print('ALERT')");
  });
});
