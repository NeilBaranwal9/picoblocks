import { describe, expect, it } from 'vitest';
import { forever, generate, importsOf, num, onStart } from '../helpers';

describe('pin blocks', () => {
  it('drives the onboard LED by name', () => {
    const code = generate([forever({ type: 'onboard_led', fields: { STATE: '1' } })]);
    expect(code).toContain('    Pin("LED", Pin.OUT).value(1)');
  });

  it('drives the onboard LED by GPIO on a classic Pico', () => {
    const code = generate([forever({ type: 'onboard_led', fields: { STATE: '0' } })], {
      onboardLed: '25',
    });
    expect(code).toContain('    Pin(25, Pin.OUT).value(0)');
  });

  it('sets a digital pin', () => {
    const code = generate([
      forever({ type: 'digital_write', fields: { PIN: '15', STATE: '1' } }),
    ]);
    expect(code).toContain('    Pin(15, Pin.OUT).value(1)');
  });

  it('reads a digital pin', () => {
    const code = generate([
      forever({
        type: 'debug_print',
        inputs: { TEXT: { block: { type: 'digital_read', fields: { PIN: '7' } } } },
      }),
    ]);
    expect(code).toContain('    print(Pin(7, Pin.IN).value())');
  });

  it('caches one PWM object per pin outside the loop', () => {
    const code = generate([
      forever(
        { type: 'pwm_write', fields: { PIN: '15' }, inputs: { DUTY: num(0) } },
        { type: 'pwm_write', fields: { PIN: '15' }, inputs: { DUTY: num(65535) } },
        { type: 'pwm_write', fields: { PIN: '16' }, inputs: { DUTY: num(30000) } },
      ),
    ]);
    expect(code).toBe(
      [
        '# Code automatically generated by PicoBlocks',
        'from machine import Pin, PWM',
        '',
        'pwm_15 = PWM(Pin(15))',
        'pwm_15.freq(1000)',
        'pwm_16 = PWM(Pin(16))',
        'pwm_16.freq(1000)',
        '',
        'while True:',
        '    pwm_15.duty_u16(0)',
        '    pwm_15.duty_u16(65535)',
        '    pwm_16.duty_u16(30000)',
        '',
      ].join('\n'),
    );
  });

  it('feeds an analog reading straight into a PWM duty cycle', () => {
    const code = generate([
      forever({
        type: 'pwm_write',
        fields: { PIN: '15' },
        inputs: { DUTY: { block: { type: 'analog_read', fields: { PIN: '26' } } } },
      }),
    ]);
    expect(code).toContain('    pwm_15.duty_u16(ADC(Pin(26)).read_u16())');
    expect(importsOf(code)).toEqual(['from machine import Pin, PWM, ADC']);
  });

  it('imports only what the program uses', () => {
    expect(importsOf(generate([forever({ type: 'onboard_led', fields: { STATE: '1' } })]))).toEqual(
      ['from machine import Pin'],
    );
    expect(
      importsOf(generate([onStart({ type: 'wait_seconds', inputs: { SECONDS: num(1) } })])),
    ).toEqual(['import time']);
    expect(importsOf(generate([{ type: 'forever' }]))).toEqual([]);
  });
});
